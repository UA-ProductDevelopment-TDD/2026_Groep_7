"""Transport-independent boundary; only MockAdapter is implemented and enabled."""
from typing import Protocol

class RobotAdapter(Protocol):
    source: str
    def snapshot(self) -> dict: ...
    def execute(self, command: dict) -> dict: ...
    def tick(self, seconds: float) -> None: ...
    def set_project(self, project: dict) -> None: ...
    def shutdown(self) -> None: ...

# Future adapters translate this boundary to a confirmed simulator/ESP32/BiBoard
# protocol. They must return unknown for missing sensors, never invented values.
